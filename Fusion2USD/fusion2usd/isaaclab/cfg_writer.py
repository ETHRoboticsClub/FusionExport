"""Generates an Isaac Lab 2.x ``ArticulationCfg`` module for an exported robot."""

from __future__ import annotations

import math
import os
import re
from typing import Dict, List, Optional, Tuple

from ..core.naming import sanitize
from ..core.report import ExportReport
from ..model.robot import Joint, RobotModel
from ..options import ExportOptions
from ..usd.plan import ExportPlan

_ActuatorKey = Tuple[Optional[float], Optional[float], float, float, Optional[float], Optional[float]]


def _tuple(values) -> str:
    return "(" + ", ".join(_num(float(v)) for v in values) + ")"


def _num(v: float) -> str:
    v = float(v)
    if math.isinf(v):
        return 'float("inf")' if v > 0 else '-float("inf")'
    return repr(v)


class IsaacLabCfgWriter:
    def __init__(self, options: ExportOptions, report: ExportReport) -> None:
        self.options = options
        self.report = report

    def write(self, model: RobotModel, usd_path: str, cfg_path: str) -> str:
        """Write the config module to ``cfg_path`` and return its path."""
        source = self.render(model, usd_path, cfg_path)
        os.makedirs(os.path.dirname(os.path.abspath(cfg_path)), exist_ok=True)
        with open(cfg_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(source)
        return cfg_path

    def render(self, model: RobotModel, usd_path: str, cfg_path: str) -> str:
        plan = ExportPlan(model, self.options)  # warnings were already reported by the USD builder
        rel = os.path.relpath(os.path.abspath(usd_path), os.path.dirname(os.path.abspath(cfg_path)))
        rel_parts = ", ".join(repr(p) for p in rel.replace("\\", "/").split("/"))
        var = sanitize(model.name or "robot", "robot").upper() + "_CFG"

        articulated = [j for j in model.joints if plan.in_articulation(j)]
        base_pose = model.root_pose
        groups: Dict[_ActuatorKey, List[str]] = {}
        passive: List[str] = []
        for j in articulated:
            if plan.is_driven(j):
                groups.setdefault(self._actuator_key(j), []).append(plan.joint_names[j.name])
            else:
                passive.append(plan.joint_names[j.name] + (" (mimic)" if j.name in plan.followers else ""))

        out: List[str] = [
            f"# Isaac Lab articulation config for {model.name!r}, generated by fusion2usd.",
            "",
            "import os",
            "",
            "import isaaclab.sim as sim_utils",
            "from isaaclab.actuators import ImplicitActuatorCfg",
            "from isaaclab.assets.articulation import ArticulationCfg",
            "",
            f"USD_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), {rel_parts})",
            "",
        ]
        if passive:
            out.append("# Joints without an actuator (passive or mimic followers):")
            out += [f"#   {name}" for name in passive]
            out.append("")
        out += [
            f"{var} = ArticulationCfg(",
            "    spawn=sim_utils.UsdFileCfg(",
            "        usd_path=USD_PATH,",
            "        activate_contact_sensors=False,",
            "        rigid_props=sim_utils.RigidBodyPropertiesCfg(",
            "            disable_gravity=False,",
            "            retain_accelerations=False,",
            "            linear_damping=0.0,",
            "            angular_damping=0.0,",
            "            max_linear_velocity=1000.0,",
            "            max_angular_velocity=1000.0,",
            "            max_depenetration_velocity=1.0,",
            "        ),",
            "        articulation_props=sim_utils.ArticulationRootPropertiesCfg(",
            f"            enabled_self_collisions={bool(self.options.self_collisions)!r},",
            "            solver_position_iteration_count=8,",
            "            solver_velocity_iteration_count=0,",
            "            fix_root_link=None,  # the USD root_joint already fixes the base if needed",
            "        ),",
            "    ),",
            "    init_state=ArticulationCfg.InitialStateCfg(",
            f"        pos={_tuple(base_pose.translation)},",
            f"        rot={_tuple(base_pose.rotation.normalized().canonical().as_tuple())},  # (w, x, y, z)",
            "        joint_pos={",
        ]
        out += [f"            {re.escape(plan.joint_names[j.name])!r}: {_num(j.dofs[0].value)},"
                for j in articulated]
        out += ["        },", "    ),", "    actuators={"]
        for i, (key, names) in enumerate(groups.items()):
            out += self._actuator(f"group_{i}", key, names)
        out += ["    },", ")", ""]
        return "\n".join(out)

    def _actuator_key(self, joint: Joint) -> _ActuatorKey:
        p, d = joint.properties, self.options.drive
        return (
            d.max_force if p.effort is None else p.effort,
            p.velocity,
            d.stiffness if p.stiffness is None else p.stiffness,
            d.damping if p.damping is None else p.damping,
            p.armature,
            p.friction,
        )

    @staticmethod
    def _actuator(name: str, key: _ActuatorKey, joints: List[str]) -> List[str]:
        effort, velocity, stiffness, damping, armature, friction = key
        lines = [
            f"        {name!r}: ImplicitActuatorCfg(",
            "            joint_names_expr=[" + ", ".join(repr(re.escape(j)) for j in joints) + "],",
        ]
        if effort is not None:
            lines.append(f"            effort_limit_sim={_num(effort)},")
        if velocity is not None:
            lines.append(f"            velocity_limit_sim={_num(velocity)},")
        lines.append(f"            stiffness={_num(stiffness)},")
        lines.append(f"            damping={_num(damping)},")
        if armature is not None:
            lines.append(f"            armature={_num(armature)},")
        if friction is not None:
            lines.append(f"            friction={_num(friction)},")
        lines.append("        ),")
        return lines
